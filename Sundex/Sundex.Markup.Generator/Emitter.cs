using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Sundex.Markup.Generator;

internal sealed class Settings(string rootNamespace, string? markupNamespace, string? context)
{
    public string Namespace { get; } = string.IsNullOrEmpty(markupNamespace) ? rootNamespace : markupNamespace!;
    public string? Context { get; } = context;
}

/// <summary>
///     Turns one document into a C# class. Tags and attributes are resolved against the real
///     component types, so a misspelt tag, an unknown attribute or a literal that doesn't parse is
///     a build error at its line in the markup, and every <c>{expression}</c> is compiled C#.
/// </summary>
internal sealed class Emitter
{
    private const string Runtime = "global::Sundex.Markup.MarkupRuntime";
    private readonly Dictionary<string, MarkupDocument> _components;
    private readonly List<Diagnostic> _diagnostics;
    private readonly INamedTypeSymbol? _panel;
    private readonly Settings _settings;
    private readonly Dictionary<string, INamedTypeSymbol> _tags;
    private readonly INamedTypeSymbol? _uiContext;
    private int _counter;
    private MarkupDocument _document = null!;
    private StringBuilder _out = null!;
    private int _indent;

    private readonly System.Collections.Immutable.ImmutableArray<StyleIndex> _sheets;
    private readonly System.Collections.Immutable.ImmutableArray<(string Path, string Text)> _logicFiles;
    private HashSet<string>? _classes;

    public Emitter(Compilation compilation, Settings settings, Dictionary<string, MarkupDocument> components,
        List<Diagnostic> diagnostics, System.Collections.Immutable.ImmutableArray<StyleIndex> sheets,
        System.Collections.Immutable.ImmutableArray<(string Path, string Text)> logicFiles)
    {
        _sheets = sheets;
        _logicFiles = logicFiles;
        _settings = settings;
        _components = components;
        _diagnostics = diagnostics;
        _panel = compilation.GetTypeByMetadataName("Sundex.Components.Panels.Panel");
        _uiContext = compilation.GetTypeByMetadataName("Sundex.Components.Abstractions.UIContext");
        _tags = FindTags(compilation);
    }

    public string? Emit(MarkupDocument document)
    {
        _document = document;
        _classes = StyleIndex.NamesFor(document.StyleSource, _sheets);
        _out = new StringBuilder();
        _counter = 0;
        _indent = 0;

        if (document.InlineStyle)
            Report(Diagnostics.InlineStyle, document.StyleSpot);
        if (document.LayoutRoots != 1 || document.Root == null)
        {
            Report(Diagnostics.LayoutRoot, document.LayoutSpot, document.LayoutRoots);
            return null;
        }

        var context = document.Context ?? _settings.Context ?? "object";
        var contextType = context == "object" ? "object" : "global::" + context;
        var namespaceName = document.Namespace ?? _settings.Namespace;

        Line("// <auto-generated/> by Sundex.Markup.Generator from " + System.IO.Path.GetFileName(document.Path));
        Line("#nullable enable");
        Line("#pragma warning disable CS8321, CS0219, CS0162, CS1998, CS0168");
        Line($"namespace {namespaceName}");
        Open();
        // Inside the namespace, so State(…) and friends win over a namespace of the same name around it.
        Line("using System;");
        Line("using System.Linq;");
        Line("using System.Collections.Generic;");
        Line("using Sundex.Reactive;");
        Line("using static Sundex.Reactive.Rx;");
        // The component types, so logic can name what a ref="…" holds without imports of its own.
        Line("using Sundex.Components;");
        Line("using Sundex.Components.Abstractions;");
        Line("using Sundex.Components.Panels;");
        Line("using Sundex.Components.Labels;");
        Line("using Sundex.Components.Inputs;");
        Line("using Sundex.Components.Scroll;");
        foreach (var import in document.Imports) Line($"using {import};");
        Line("");
        Line($"public partial class {document.ClassName} : global::Sundex.Markup.MarkupComponent<{contextType}>");
        Open();
        Line($"public const string MarkupTag = {Quote(document.Tag)};");
        Line($"public {document.ClassName}(global::Sundex.Markup.SundexContext<{contextType}> sundex) : base(sundex) {{ }}");
        EmitProps(document);
        Line("");
        Line("protected override global::Sundex.Components.Abstractions.UIElement Build()");
        Open();
        Line($"var __sheet = LoadStyleSheet({(document.StyleSource == null ? "null" : Quote(document.StyleSource))});");
        var logic = document.Logic;
        var logicPath = document.Path;
        var logicSpot = document.LogicSpot;
        if (document.LogicSource != null)
        {
            var file = _logicFiles.FirstOrDefault(candidate => StyleIndex.IsAt(candidate.Path, document.LogicSource));
            if (file.Path == null)
            {
                Report(Diagnostics.MissingLogic, document.LogicSourceSpot, document.LogicSource);
                return null;
            }

            logic = file.Text;
            logicPath = file.Path;
            logicSpot = new Spot(1, 1);
        }

        if (!string.IsNullOrWhiteSpace(logic))
        {
            LineDirective(logicSpot, logicPath);
            // Verbatim and unindented: the #line above maps it back to its file line for line.
            _out.Append(logic!.TrimEnd()).Append('\n');
            Line("#line default");
        }

        var root = EmitNode(document.Root, null);
        Line($"return {root ?? "null!"};");
        Close();
        Close();
        Close();
        return _out.ToString();
    }

    // A reserved word (base, class, event…) can't name the member the markup's expressions read;
    // contextual ones (value, var, async) can.
    private static bool IsKeyword(string name) =>
        Microsoft.CodeAnalysis.CSharp.SyntaxFacts.GetKeywordKind(name.Replace('-', '_')) != Microsoft.CodeAnalysis.CSharp.SyntaxKind.None;

    private void EmitProps(MarkupDocument document)
    {
        foreach (var prop in document.Props)
        {
            if (prop.Name is "id" or "class" or "slot" or "ref")
            {
                Report(Diagnostics.ReservedProp, prop.Spot, prop.Name);
                continue;
            }

            if (IsKeyword(prop.Name))
            {
                Report(Diagnostics.KeywordName, prop.Spot, prop.Name);
                continue;
            }

            var type = prop.Type;
            var initial = prop.Default == null
                ? "default!"
                : IsExpression(prop.Default) ? Inner(prop.Default) : type.TrimEnd('?') is "string" or "System.String" ? Quote(prop.Default) : prop.Default;
            Line($"private global::System.Func<{type}> __prop_{prop.Name.Replace('-', '_')} = static () => {initial};");
            Line($"/// <summary>The <c>{prop.Name}</c> prop, as a getter: reading it inside a binding tracks what it reads.</summary>");
            Line($"public global::System.Func<{type}> {MarkupDocument.Pascal(prop.Name)} {{ set => __prop_{prop.Name.Replace('-', '_')} = value; }}");
            Line($"private {type} {prop.Name.Replace('-', '_')} => __prop_{prop.Name.Replace('-', '_')}();");
        }

        foreach (var markupEvent in document.Events)
        {
            if (IsKeyword(markupEvent.Name))
            {
                Report(Diagnostics.KeywordName, markupEvent.Spot, markupEvent.Name);
                continue;
            }

            var handler = markupEvent.Type == null ? "global::System.Action" : $"global::System.Action<{markupEvent.Type}>";
            Line($"/// <summary>The <c>{markupEvent.Name}</c> event: <c>on.{markupEvent.Name}</c> where the component is used.</summary>");
            Line($"public {handler}? On{MarkupDocument.Pascal(markupEvent.Name)} {{ get; set; }}");
            // own-code is raised as own_code(): a hyphen can't be in a C# name.
            var raise = markupEvent.Name.Replace('-', '_');
            Line(markupEvent.Type == null
                ? $"private void {raise}() => On{MarkupDocument.Pascal(markupEvent.Name)}?.Invoke();"
                : $"private void {raise}({markupEvent.Type} value) => On{MarkupDocument.Pascal(markupEvent.Name)}?.Invoke(value);");
        }
    }

    // ── Nodes ─────────────────────────────────────────────────────────────────────────────────

    private void EmitChildren(List<MarkupNode> children, string parent)
    {
        for (var index = 0; index < children.Count; index++)
        {
            var node = children[index];
            switch (node.Tag)
            {
                case "if":
                {
                    var branches = new List<MarkupNode> { node };
                    while (index + 1 < children.Count && children[index + 1].Tag is "else-if" or "else")
                    {
                        branches.Add(children[++index]);
                        if (branches[branches.Count - 1].Tag == "else") break;
                    }

                    EmitIf(branches, parent);
                    break;
                }
                case "else-if":
                case "else":
                    Report(Diagnostics.OrphanElse, node.Spot, node.Tag);
                    break;
                case "each":
                {
                    MarkupNode? empty = null;
                    if (index + 1 < children.Count && children[index + 1].Tag == "empty") empty = children[++index];
                    EmitEach(node, empty, parent);
                    break;
                }
                case "empty":
                    Report(Diagnostics.OrphanEmpty, node.Spot);
                    break;
                case "slot":
                {
                    var name = node.Attribute("name")?.Value;
                    Line(name == null ? $"Slot?.Invoke({parent});" : $"FillSlot({Quote(name)}, {parent});");
                    break;
                }
                default:
                    EmitNode(node, parent);
                    break;
            }
        }
    }

    /// <summary>Emits an element or a component use; returns its variable, or null when it couldn't be built.</summary>
    private string? EmitNode(MarkupNode node, string? parent)
    {
        if (node.Tag is "if" or "else-if" or "else" or "each" or "empty" or "slot")
        {
            Report(Diagnostics.FlowAsRoot, node.Spot, node.Tag);
            return null;
        }

        if (_components.TryGetValue(node.Tag, out var component)) return EmitComponentUse(node, component, parent);

        if (!_tags.TryGetValue(node.Tag, out var type))
        {
            Report(Diagnostics.UnknownTag, node.Spot, node.Tag);
            return null;
        }

        if (!HasContextConstructor(type))
        {
            Report(Diagnostics.NoConstructor, node.Spot, type.Name);
            return null;
        }

        CheckClasses(node);
        var element = Next("__e");
        var typeName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        Line($"var {element} = new {typeName}(Ui);");
        Line($"{Runtime}.Init({element}, __sheet, {QuoteOrNull(node.Attribute("id")?.Value)}, {QuoteOrNull(node.Attribute("class")?.Value)});");

        foreach (var attribute in node.Attributes)
        {
            if (attribute.Name is "id" or "class" or "slot") continue;
            if (attribute.Name.StartsWith("class.", StringComparison.Ordinal)) EmitClassToggle(element, attribute);
            else if (attribute.Name.StartsWith("on.", StringComparison.Ordinal)) EmitEvent(element, type, attribute);
            else if (attribute.Name.StartsWith("bind.", StringComparison.Ordinal)) EmitTwoWay(element, type, attribute);
            else if (attribute.Name == "ref") Line($"{attribute.Value} = {element};");
            else EmitProperty(element, type, attribute);
        }

        if (node.Children.Count > 0)
        {
            if (_panel != null && !DerivesFrom(type, _panel))
                Report(Diagnostics.NotAContainer, node.Spot, node.Tag);
            else
                EmitChildren(node.Children, element);
        }

        if (parent != null) Line($"{Runtime}.Add({parent}, {element});");
        return element;
    }

    private string EmitComponentUse(MarkupNode node, MarkupDocument component, string? parent)
    {
        var instance = Next("__c");
        var className = (component.Namespace ?? _settings.Namespace) + "." + component.ClassName;
        Line($"var {instance} = new global::{className}(Sundex);");
        foreach (var attribute in node.Attributes)
        {
            if (attribute.Name is "id" or "class" or "slot") continue;
            if (attribute.Name == "ref")
            {
                Line($"{attribute.Value} = {instance};");
                continue;
            }

            if (attribute.Name.StartsWith("on.", StringComparison.Ordinal))
            {
                EmitComponentEvent(instance, component, attribute);
                continue;
            }

            var prop = component.Props.FirstOrDefault(candidate => candidate.Name == attribute.Name);
            if (prop == null)
            {
                Report(Diagnostics.UnknownProp, attribute.Spot, attribute.Name, component.Tag);
                continue;
            }

            var value = IsExpression(attribute.Value) ? Inner(attribute.Value)
                : HasInterpolation(attribute.Value) ? Interpolate(attribute.Value)
                : prop.Type.TrimEnd('?') is "string" or "System.String" ? Quote(attribute.Value)
                : attribute.Value;
            LineDirective(attribute.Spot);
            Line($"{instance}.{MarkupDocument.Pascal(prop.Name)} = () => ({value});");
            Line("#line default");
        }

        // Children marked slot="name" fill that named slot; the rest are the default one.
        var unnamed = node.Children.Where(child => child.Attribute("slot") == null).ToList();
        if (unnamed.Count > 0)
        {
            var slot = Next("__slot");
            Line($"{instance}.Slot = {slot} =>");
            Open();
            EmitChildren(unnamed, slot);
            CloseWith("};");
        }

        foreach (var named in node.Children.Where(child => child.Attribute("slot") != null).GroupBy(child => child.Attribute("slot")!.Value))
        {
            var slot = Next("__slot");
            Line($"{instance}.Slots[{Quote(named.Key)}] = {slot} =>");
            Open();
            EmitChildren(named.ToList(), slot);
            CloseWith("};");
        }

        CheckUseClasses(node, component);
        var element = Next("__e");
        Line($"var {element} = {instance}.Create();");
        if (node.Attribute("id") != null || node.Attribute("class") != null)
            Line($"{Runtime}.Usage({element}, {QuoteOrNull(node.Attribute("id")?.Value)}, {QuoteOrNull(node.Attribute("class")?.Value)});");
        if (parent != null) Line($"{Runtime}.Add({parent}, {element});");
        return element;
    }

    private void EmitComponentEvent(string instance, MarkupDocument component, MarkupAttribute attribute)
    {
        var name = attribute.Name.Substring("on.".Length);
        var declared = component.Events.FirstOrDefault(candidate => candidate.Name == name);
        if (declared == null)
        {
            Report(Diagnostics.UnknownEvent, attribute.Spot, attribute.Name, "<" + component.Tag + ">");
            return;
        }

        if (!IsExpression(attribute.Value))
        {
            Report(Diagnostics.MissingAttribute, attribute.Spot, attribute.Name, "a {handler}");
            return;
        }

        var handler = Inner(attribute.Value);
        LineDirective(attribute.Spot);
        Line(declared.Type == null
            ? $"{instance}.On{MarkupDocument.Pascal(name)} += {handler};"
            : $"{instance}.On{MarkupDocument.Pascal(name)} += {Runtime}.Handler<{declared.Type}>({handler});");
        Line("#line default");
    }

    private void EmitIf(List<MarkupNode> branches, string parent)
    {
        var keep = branches[0].Attribute("keep")?.Value == "true";
        var selector = new StringBuilder();
        var index = 0;
        foreach (var branch in branches)
        {
            if (branch.Tag == "else")
            {
                selector.Append(index);
                break;
            }

            var condition = branch.Attribute("condition");
            if (condition == null || !IsExpression(condition.Value))
            {
                Report(Diagnostics.MissingAttribute, branch.Spot, branch.Tag, "condition=\"{…}\"");
                return;
            }

            selector.Append($"({Inner(condition.Value)}) ? {index} : ");
            index++;
        }

        if (branches[branches.Count - 1].Tag != "else") selector.Append("-1");

        LineDirective(branches[0].Spot);
        Line($"{Runtime}.If({parent}, () => {selector}, {(keep ? "true" : "false")},");
        Line("#line default");
        _indent++;
        for (var branch = 0; branch < branches.Count; branch++)
        {
            var region = Next("__p");
            Line($"{region} =>");
            Open();
            EmitChildren(branches[branch].Children, region);
            CloseWith(branch == branches.Count - 1 ? "});" : "},");
        }

        _indent--;
    }

    private void EmitEach(MarkupNode node, MarkupNode? empty, string parent)
    {
        var items = node.Attribute("items");
        if (items == null || !IsExpression(items.Value))
        {
            Report(Diagnostics.MissingAttribute, node.Spot, "each", "items=\"{…}\"");
            return;
        }

        var item = node.Attribute("as")?.Value ?? "item";
        var key = node.Attribute("key");
        var index = node.Attribute("index")?.Value ?? Next("__index");
        var region = Next("__p");

        LineDirective(node.Spot);
        Line($"{Runtime}.Each({parent}, () => {Runtime}.Items({Inner(items.Value)}),");
        Line($"    ({item}) => {(key != null && IsExpression(key.Value) ? $"(object?)({Inner(key.Value)})" : $"(object?){item}")},");
        Line("#line default");
        _indent++;
        Line($"({region}, {item}, {index}) =>");
        Open();
        EmitChildren(node.Children, region);
        if (empty == null)
        {
            CloseWith("}, null);");
        }
        else
        {
            CloseWith("},");
            var emptyRegion = Next("__p");
            Line($"{emptyRegion} =>");
            Open();
            EmitChildren(empty.Children, emptyRegion);
            CloseWith("});");
        }

        _indent--;
    }

    // ── Attributes ────────────────────────────────────────────────────────────────────────────

    private void EmitProperty(string element, INamedTypeSymbol type, MarkupAttribute attribute)
    {
        var property = FindProperty(type, attribute.Name);
        if (property == null)
        {
            Report(Diagnostics.UnknownAttribute, attribute.Spot, attribute.Name, type.Name);
            return;
        }

        if (property.SetMethod == null || property.SetMethod.DeclaredAccessibility != Accessibility.Public)
        {
            Report(Diagnostics.ReadOnlyAttribute, attribute.Spot, attribute.Name, type.Name);
            return;
        }

        if (IsExpression(attribute.Value) || HasInterpolation(attribute.Value))
        {
            var value = IsExpression(attribute.Value) ? $"({Inner(attribute.Value)})" : Interpolate(attribute.Value);
            LineDirective(attribute.Spot);
            Line($"{Runtime}.Bind(() => {element}.{property.Name} = {value});");
            Line("#line default");
            return;
        }

        var literal = Literal(property.Type, attribute.Value);
        if (literal == null)
        {
            Report(Diagnostics.BadLiteral, attribute.Spot, attribute.Value, attribute.Name, property.Type.ToDisplayString());
            return;
        }

        Line($"{element}.{property.Name} = {literal};");
    }

    /// <summary>
    ///     A class on a component tag lands on the component's root, which the component's own sheet
    ///     styles: one that sheet doesn't name does nothing, whatever this document's sheet says.
    /// </summary>
    private void CheckUseClasses(MarkupNode node, MarkupDocument component)
    {
        if (node.Attribute("class") is not { } attribute) return;
        var names = StyleIndex.NamesFor(component.StyleSource, _sheets);
        if (names == null) return;
        foreach (var name in attribute.Value.Split(new[] { ' ', ',' }, StringSplitOptions.RemoveEmptyEntries))
            if (!names.Contains(name))
                Report(Diagnostics.UnknownUseClass, attribute.Spot, name, component.StyleSource ?? "", component.Tag);
    }

    /// <summary>A class no rule in the document's sheet (or what it imports) names does nothing: say so at build time.</summary>
    private void CheckClasses(MarkupNode node)
    {
        if (_classes == null) return;
        foreach (var attribute in node.Attributes)
        {
            IEnumerable<string> names = attribute.Name == "class"
                ? attribute.Value.Trim('[', ']').Split(new[] { ' ', ',' }, StringSplitOptions.RemoveEmptyEntries)
                : attribute.Name.StartsWith("class.", StringComparison.Ordinal)
                    ? new[] { attribute.Name.Substring("class.".Length) }
                    : Array.Empty<string>();
            foreach (var name in names)
                if (!_classes.Contains(name))
                    Report(Diagnostics.UnknownClass, attribute.Spot, name, _document.StyleSource ?? "");
        }
    }

    private void EmitClassToggle(string element, MarkupAttribute attribute)
    {
        var name = attribute.Name.Substring("class.".Length);
        var value = IsExpression(attribute.Value) ? Inner(attribute.Value)
            : attribute.Value is "true" or "false" ? attribute.Value : null;
        if (value == null)
        {
            Report(Diagnostics.BadLiteral, attribute.Spot, attribute.Value, attribute.Name, "bool");
            return;
        }

        LineDirective(attribute.Spot);
        Line($"{Runtime}.Class({element}, {Quote(name)}, () => ({value}));");
        Line("#line default");
    }

    private void EmitEvent(string element, INamedTypeSymbol type, MarkupAttribute attribute)
    {
        var name = "On" + MarkupDocument.Pascal(attribute.Name.Substring("on.".Length));
        var member = FindMember(type, name);
        var delegateType = (member as IPropertySymbol)?.Type ?? (member as IEventSymbol)?.Type;
        if (delegateType is not INamedTypeSymbol { DelegateInvokeMethod: { } invoke })
        {
            Report(Diagnostics.UnknownEvent, attribute.Spot, attribute.Name, type.Name);
            return;
        }

        if (!IsExpression(attribute.Value))
        {
            Report(Diagnostics.MissingAttribute, attribute.Spot, attribute.Name, "a {handler}");
            return;
        }

        var handler = Inner(attribute.Value);
        LineDirective(attribute.Spot);
        if (invoke.Parameters.Length == 1)
        {
            var parameter = invoke.Parameters[0].Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            Line($"{element}.{member!.Name} += {Runtime}.Handler<{parameter}>({handler});");
        }
        else
        {
            Line($"{element}.{member!.Name} += {handler};");
        }

        Line("#line default");
    }

    private void EmitTwoWay(string element, INamedTypeSymbol type, MarkupAttribute attribute)
    {
        var propertyName = attribute.Name.Substring("bind.".Length);
        var property = FindProperty(type, propertyName);
        if (property == null || !IsExpression(attribute.Value))
        {
            Report(Diagnostics.UnknownAttribute, attribute.Spot, attribute.Name, type.Name);
            return;
        }

        var change = FindMember(type, "On" + property.Name + "Changed") ?? FindMember(type, "OnChange");
        var delegateType = (change as IPropertySymbol)?.Type ?? (change as IEventSymbol)?.Type;
        if (delegateType is not INamedTypeSymbol { DelegateInvokeMethod: { } invoke })
        {
            Report(Diagnostics.NoChangeEvent, attribute.Spot, property.Name, type.Name);
            return;
        }

        var state = Inner(attribute.Value);
        LineDirective(attribute.Spot);
        Line($"{Runtime}.Bind(() => {element}.{property.Name} = ({state}).Value);");
        var write = $"() => ({state}).Value = {element}.{property.Name}";
        if (invoke.Parameters.Length == 1)
        {
            var parameter = invoke.Parameters[0].Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            Line($"{element}.{change!.Name} += {Runtime}.Handler<{parameter}>({write});");
        }
        else
        {
            Line($"{element}.{change!.Name} += {write};");
        }

        Line("#line default");
    }

    // ── Symbols ───────────────────────────────────────────────────────────────────────────────

    private static Dictionary<string, INamedTypeSymbol> FindTags(Compilation compilation)
    {
        var tags = new Dictionary<string, INamedTypeSymbol>(StringComparer.Ordinal);
        var assemblies = new List<IAssemblySymbol> { compilation.Assembly };
        assemblies.AddRange(compilation.SourceModule.ReferencedAssemblySymbols
            .Where(assembly => assembly.Name.StartsWith("Sundex", StringComparison.Ordinal)));
        foreach (var assembly in assemblies) Walk(assembly.GlobalNamespace, tags);
        return tags;
    }

    private static void Walk(INamespaceSymbol namespaceSymbol, Dictionary<string, INamedTypeSymbol> tags)
    {
        foreach (var type in namespaceSymbol.GetTypeMembers())
        foreach (var attribute in type.GetAttributes())
            if (attribute.AttributeClass?.Name == "MarkupTagAttribute" &&
                attribute.ConstructorArguments.Length == 1 &&
                attribute.ConstructorArguments[0].Value is string tag)
                tags[tag] = type;

        foreach (var child in namespaceSymbol.GetNamespaceMembers()) Walk(child, tags);
    }

    private bool HasContextConstructor(INamedTypeSymbol type) =>
        !type.IsAbstract && type.InstanceConstructors.Any(constructor =>
            constructor.DeclaredAccessibility == Accessibility.Public &&
            constructor.Parameters.Length >= 1 &&
            SymbolEqualityComparer.Default.Equals(constructor.Parameters[0].Type, _uiContext) &&
            constructor.Parameters.Skip(1).All(parameter => parameter.HasExplicitDefaultValue));

    private static bool DerivesFrom(INamedTypeSymbol type, INamedTypeSymbol baseType)
    {
        for (var current = type; current != null; current = current.BaseType)
            if (SymbolEqualityComparer.Default.Equals(current, baseType))
                return true;
        return false;
    }

    /// <summary>An attribute names a property by its stylesheet name (<c>font-size</c>) or by its C# name, in kebab case.</summary>
    private static IPropertySymbol? FindProperty(INamedTypeSymbol type, string attribute)
    {
        var pascal = MarkupDocument.Pascal(attribute);
        IPropertySymbol? byName = null;
        for (var current = type; current != null; current = current.BaseType)
        foreach (var member in current.GetMembers().OfType<IPropertySymbol>())
        {
            if (member.DeclaredAccessibility != Accessibility.Public || member.IsStatic) continue;
            foreach (var attributeData in member.GetAttributes())
                if (attributeData.AttributeClass?.Name == "NamedSettingAttribute" &&
                    attributeData.ConstructorArguments.Length > 0 && attributeData.ConstructorArguments[0].Value as string == attribute)
                    return member;
            if (byName == null && string.Equals(member.Name, pascal, StringComparison.OrdinalIgnoreCase)) byName = member;
        }

        return byName;
    }

    private static ISymbol? FindMember(INamedTypeSymbol type, string name)
    {
        for (var current = type; current != null; current = current.BaseType)
        foreach (var member in current.GetMembers(name))
            if (member.DeclaredAccessibility == Accessibility.Public && member is IPropertySymbol or IEventSymbol)
                return member;
        return null;
    }

    /// <summary>A plain attribute value as a C# expression of the property's type, checked here rather than at runtime.</summary>
    private static string? Literal(ITypeSymbol type, string raw)
    {
        if (type is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } nullable)
            type = nullable.TypeArguments[0];
        var invariant = CultureInfo.InvariantCulture;
        switch (type.SpecialType)
        {
            case SpecialType.System_String:
                return Quote(raw);
            case SpecialType.System_Boolean:
                return raw is "true" or "false" ? raw : null;
            case SpecialType.System_Int32:
                return int.TryParse(raw, NumberStyles.Integer, invariant, out _) ? raw : null;
            case SpecialType.System_Int64:
                return long.TryParse(raw, NumberStyles.Integer, invariant, out _) ? raw + "L" : null;
            case SpecialType.System_Single:
                return float.TryParse(raw, NumberStyles.Float, invariant, out _) ? raw + "f" : null;
            case SpecialType.System_Double:
                return double.TryParse(raw, NumberStyles.Float, invariant, out _) ? raw + "d" : null;
        }

        if (type is INamedTypeSymbol { Name: "ReadOnlySpan" } span && span.TypeArguments.Length == 1 &&
            span.TypeArguments[0].SpecialType == SpecialType.System_Char)
            return Quote(raw);

        var full = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        if (type.TypeKind == TypeKind.Enum)
        {
            var wanted = MarkupDocument.Pascal(raw);
            var member = type.GetMembers().OfType<IFieldSymbol>()
                .FirstOrDefault(field => string.Equals(field.Name, wanted, StringComparison.OrdinalIgnoreCase));
            return member == null ? null : $"{full}.{member.Name}";
        }

        return $"{Runtime}.Parse<{full}>({Quote(raw)})";
    }

    // ── Text ──────────────────────────────────────────────────────────────────────────────────

    private static bool IsExpression(string value)
    {
        var text = value.Trim();
        if (text.Length < 2 || text[0] != '{' || text[text.Length - 1] != '}') return false;
        var depth = 0;
        for (var index = 0; index < text.Length; index++)
        {
            if (text[index] == '{') depth++;
            else if (text[index] == '}' && --depth == 0 && index != text.Length - 1) return false;
        }

        return depth == 0;
    }

    private static bool HasInterpolation(string value) => value.IndexOf('{') >= 0 && value.IndexOf('}') > value.IndexOf('{');

    private static string Inner(string value)
    {
        var text = value.Trim();
        return text.Substring(1, text.Length - 2).Trim();
    }

    /// <summary><c>Hello {name}!</c> as <c>$"Hello {(name)}!"</c>.</summary>
    private static string Interpolate(string value)
    {
        var builder = new StringBuilder("$\"");
        var index = 0;
        while (index < value.Length)
        {
            var character = value[index];
            if (character == '{')
            {
                var depth = 0;
                var start = index;
                for (; index < value.Length; index++)
                {
                    if (value[index] == '{') depth++;
                    else if (value[index] == '}' && --depth == 0) break;
                }

                var (hole, format) = SplitFormat(value.Substring(start + 1, index - start - 1).Trim());
                builder.Append("{(").Append(hole).Append(')').Append(format).Append('}');
                index++;
                continue;
            }

            builder.Append(character switch
            {
                '"' => "\\\"",
                '\\' => "\\\\",
                '\n' => "\\n",
                '\r' => "",
                '}' => "}}",
                _ => character.ToString()
            });
            index++;
        }

        return builder.Append('"').ToString();
    }

    /// <summary>
    ///     <c>{ms:0}</c>: a format after a top-level colon stays outside the parentheses the hole is
    ///     wrapped in. A colon that ends a ternary (<c>{a ? b : c}</c>) is the expression's own.
    /// </summary>
    private static (string Hole, string Format) SplitFormat(string hole)
    {
        var depth = 0;
        var ternaries = 0;
        for (var index = 0; index < hole.Length; index++)
        {
            var character = hole[index];
            if (character == '"' || character == '\'')
            {
                for (index++; index < hole.Length && hole[index] != character; index++)
                    if (hole[index] == '\\') index++;
                continue;
            }

            if (character is '(' or '[' or '{') depth++;
            else if (character is ')' or ']' or '}') depth--;
            else if (depth == 0 && character == '?' && (index + 1 >= hole.Length || hole[index + 1] is not ('.' or '?' or '[')) && (index == 0 || hole[index - 1] != '?'))
                ternaries++;
            else if (depth == 0 && character == ':' && (index + 1 >= hole.Length || hole[index + 1] != ':') && (index == 0 || hole[index - 1] != ':'))
            {
                if (ternaries > 0)
                {
                    ternaries--;
                    continue;
                }

                return (hole.Substring(0, index).Trim(), hole.Substring(index));
            }
        }

        return (hole, "");
    }

    private static string Quote(string value)
    {
        var builder = new StringBuilder("\"");
        foreach (var character in value)
            builder.Append(character switch
            {
                '"' => "\\\"",
                '\\' => "\\\\",
                '\n' => "\\n",
                '\r' => "\\r",
                '\t' => "\\t",
                _ => character.ToString()
            });
        return builder.Append('"').ToString();
    }

    private static string QuoteOrNull(string? value) => value == null ? "null" : Quote(value);

    // ── Output ────────────────────────────────────────────────────────────────────────────────

    private string Next(string prefix) => prefix + _counter++;

    private void Line(string text)
    {
        if (text.StartsWith("#", StringComparison.Ordinal))
        {
            _out.Append(text).Append('\n');
            return;
        }

        _out.Append(' ', _indent * 4).Append(text).Append('\n');
    }

    private void LineDirective(Spot spot, string? path = null)
    {
        _out.Append("#line ").Append(Math.Max(1, spot.Line)).Append(" \"")
            .Append((path ?? _document.Path).Replace("\\", "\\\\").Replace("\"", "\\\"")).Append("\"\n");
    }

    private void Open()
    {
        Line("{");
        _indent++;
    }

    private void Close() => CloseWith("}");

    private void CloseWith(string text)
    {
        _indent--;
        Line(text);
    }

    private void Report(DiagnosticDescriptor descriptor, Spot spot, params object[] args) =>
        _diagnostics.Add(Diagnostics.At(descriptor, _document.Path, spot, args));
}
